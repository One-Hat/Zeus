"""Planner Agent: transforms a one-sentence app idea into a complete structured Spec."""

from __future__ import annotations

import re
from typing import Optional
from forge.llm import LLMClient
from forge.schemas import AcceptanceTest, Spec, Task

PLANNER_SYSTEM_PROMPT = """You are the Forge Lead Architect (Planner Agent).
Given a one-sentence application idea, output a complete, concrete, production-ready `Spec` in JSON:
1. `api_contract`: Valid OpenAPI 3.0.0 dict with `/health` and CRUD endpoints under `/api/...`.
2. `db_schema`: SQLite DDL statements (`CREATE TABLE IF NOT EXISTS ...`).
3. `file_tree`: List of relative paths (`backend/app.py`, `backend/test_app.py`, `frontend/index.html`, `requirements.txt`).
4. `tasks`: Split clearly into `backend`, `frontend`, and (only if explicitly needed for ML/AI inference) `ml`.
5. `acceptance_tests`: Concrete HTTP checks (`GET /health`, `POST /api/...`, `GET /api/...`) that verify the app works end-to-end.
"""


class PlannerAgent:
    """Generates a complete Spec from a user's one-sentence idea."""

    def __init__(self, llm_client: LLMClient):
        self.llm = llm_client

    @staticmethod
    def build_default_spec(idea: str) -> Spec:
        """Construct a deterministic, self-contained Spec for a given idea (used in mock/fallback mode)."""
        slug = re.sub(r"[^a-z0-9]+", "-", idea.lower()).strip("-")[:30] or "forge-app"
        needs_ml = any(w in idea.lower() for w in ["ml", "predict", "classifier", "sentiment", "recommend"])

        file_tree = [
            "backend/__init__.py",
            "backend/app.py",
            "backend/test_app.py",
            "frontend/index.html",
            "frontend/app.js",
            "requirements.txt",
        ]
        tasks = [
            Task(
                id="be-1",
                role="backend",
                title="Implement FastAPI Backend & SQLite Persistence",
                description=f"Build FastAPI backend for '{idea}' with /health, /api/items CRUD, and auth support.",
                target_files=["backend/__init__.py", "backend/app.py", "backend/test_app.py", "requirements.txt"],
            ),
            Task(
                id="fe-1",
                role="frontend",
                title="Implement Responsive Frontend SPA",
                description=f"Build single-page frontend UI in HTML/JS connecting to /api/items for '{idea}'.",
                target_files=["frontend/index.html", "frontend/app.js"],
                dependencies=["be-1"],
            ),
        ]
        if needs_ml:
            file_tree.append("backend/ml_model.py")
            tasks.append(
                Task(
                    id="ml-1",
                    role="ml",
                    title="Implement Lightweight Inference Module",
                    description=f"Create scoring/prediction helper in backend/ml_model.py for '{idea}'.",
                    target_files=["backend/ml_model.py"],
                )
            )

        return Spec(
            idea=idea,
            name=slug,
            description=f"Full-stack web application generated by Forge for: {idea}",
            api_contract={
                "openapi": "3.0.0",
                "info": {"title": slug, "version": "1.0.0"},
                "paths": {
                    "/health": {
                        "get": {
                            "summary": "Health check",
                            "responses": {"200": {"description": "OK"}},
                        }
                    },
                    "/api/items": {
                        "get": {
                            "summary": "List items",
                            "responses": {"200": {"description": "List of items"}},
                        },
                        "post": {
                            "summary": "Create item",
                            "responses": {"201": {"description": "Created item"}},
                        },
                    },
                },
            },
            db_schema=(
                "CREATE TABLE IF NOT EXISTS users (id INTEGER PRIMARY KEY AUTOINCREMENT, username TEXT UNIQUE, token TEXT);\n"
                "CREATE TABLE IF NOT EXISTS items (id INTEGER PRIMARY KEY AUTOINCREMENT, title TEXT NOT NULL, completed INTEGER DEFAULT 0);"
            ),
            file_tree=file_tree,
            tasks=tasks,
            acceptance_tests=[
                AcceptanceTest(
                    id="health-check",
                    endpoint="/health",
                    method="GET",
                    expected_status=200,
                    expected_body_contains="ok",
                    description="Verify service health endpoint",
                ),
                AcceptanceTest(
                    id="create-item",
                    endpoint="/api/items",
                    method="POST",
                    payload={"title": "First item", "completed": False},
                    expected_status=201,
                    expected_body_contains="First item",
                    description="Verify creating a new item",
                ),
                AcceptanceTest(
                    id="list-items",
                    endpoint="/api/items",
                    method="GET",
                    expected_status=200,
                    expected_body_contains="First item",
                    description="Verify listing created items",
                ),
            ],
        )

    def run(self, idea: str, override_model: Optional[str] = None) -> Spec:
        """Generate a validated Spec from a one-sentence idea."""
        if "planner" not in self.llm.mock_responses:
            # Provide default mock when running under FORGE_MOCK_LLM=1
            self.llm.mock_responses.setdefault("planner", self.build_default_spec(idea))

        messages = [
            {"role": "system", "content": PLANNER_SYSTEM_PROMPT},
            {"role": "user", "content": f"App idea: {idea}"},
        ]
        return self.llm.call_structured(
            role="planner",
            messages=messages,
            response_model=Spec,
            override_model=override_model,
        )
