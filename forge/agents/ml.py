"""ML Worker Agent: generates machine learning / scoring components when requested by the Spec."""

from __future__ import annotations

import json
from typing import Optional
from forge.llm import LLMClient
from forge.sandbox.runner import DockerSandboxRunner
from forge.schemas import Spec, WorkerOutput

ML_SYSTEM_PROMPT = """You are the Forge ML Worker Agent.
You receive the application `Spec` and ONLY the `ml` tasks.
Produce a `WorkerOutput` with `role="ml"` and `files` containing lightweight, self-contained Python inference utilities.
"""

DEFAULT_ML_MODEL_PY = '''"""Lightweight inference module generated by Forge MLWorker."""

from typing import Dict, Any


def predict_score(text: str) -> Dict[str, Any]:
    """Return a deterministic priority/sentiment score for input text."""
    urgent_keywords = {"urgent", "critical", "asap", "blocker", "bug"}
    words = set(text.lower().split())
    matched = words.intersection(urgent_keywords)
    score = min(1.0, 0.3 + 0.35 * len(matched))
    return {"label": "high" if score >= 0.6 else "normal", "score": round(score, 2)}
'''


class MLWorker:
    """Worker that implements ML tasks only if the spec contains ML tasks."""

    def __init__(self, llm_client: LLMClient, sandbox: Optional[DockerSandboxRunner] = None):
        self.llm = llm_client
        self.sandbox = sandbox

    @staticmethod
    def build_default_output() -> WorkerOutput:
        return WorkerOutput(
            role="ml",
            files={"backend/ml_model.py": DEFAULT_ML_MODEL_PY},
            summary="Implemented lightweight inference module in backend/ml_model.py.",
        )

    def run(self, spec: Spec, override_model: Optional[str] = None) -> WorkerOutput:
        ml_tasks = [t.model_dump() for t in spec.tasks if t.role == "ml"]
        if not ml_tasks:
            return WorkerOutput(role="ml", files={}, summary="No ML tasks in spec; skipped.")

        self.llm.mock_responses.setdefault("ml", self.build_default_output())

        payload = {
            "app_name": spec.name,
            "assigned_tasks": ml_tasks,
        }
        messages = [
            {"role": "system", "content": ML_SYSTEM_PROMPT},
            {"role": "user", "content": json.dumps(payload, indent=2)},
        ]
        output = self.llm.call_structured(
            role="ml",
            messages=messages,
            response_model=WorkerOutput,
            override_model=override_model,
        )

        if self.sandbox is not None and output.files:
            self.sandbox.write_files(output.files)

        return output
